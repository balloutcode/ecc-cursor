'use strict';

/**
 * cursor-plugin/maps/agent-names.json: bare upstream agent id -> Cursor
 * plugin agent name (`planner` -> `ecc-planner`), one entry per agents/*.md.
 *
 * The map is GENERATED deterministically by the builder (PLAN.md section 2
 * places it in the repo maps/ layer; section 10's drift workflow requires
 * upstream agent additions to surface as a committed map change). Phases 4-5
 * read it to rewrite agent references in skills and commands; check-links
 * reads it to resolve bare references against the renamed build.
 */

const fs = require('fs');
const path = require('path');
const { toCursorAgentFileName } = require('../cursor-agent-names');

const MAP_REL = path.posix.join('cursor-plugin', 'maps', 'agent-names.json');

/** Bare id -> ecc-<id> for every agents/*.md, sorted by id (deterministic). */
function buildAgentNameMap(repoRoot) {
  const agentsDir = path.join(repoRoot, 'agents');
  const ids = fs.readdirSync(agentsDir)
    .filter(f => f.endsWith('.md'))
    .map(f => f.slice(0, -3))
    .sort();
  const agents = {};
  for (const id of ids) {
    agents[id] = toCursorAgentFileName(id);
  }
  return agents;
}

function serializeAgentNameMap(agents) {
  return `${JSON.stringify({
    version: 1,
    comment: 'GENERATED by scripts/cursor-plugin/build.js from agents/ (deterministic). Bare upstream agent id -> Cursor plugin agent name. Drift: a new upstream agent rewrites this file on build - commit the change consciously (PLAN.md section 10). Consumers: agent emitter, rules/agent reference transforms (phases 3-5), check-links.',
    agents,
  }, null, 2)}\n`;
}

function agentNameMapPath(repoRoot) {
  return path.join(repoRoot, MAP_REL);
}

/** Read the committed map file. Returns the bare -> ecc-* object. */
function loadAgentNameMap(repoRoot) {
  return JSON.parse(fs.readFileSync(agentNameMapPath(repoRoot), 'utf8')).agents;
}

/**
 * Regenerate the map file. Returns { agents, changed } where changed means
 * the committed file differed (upstream drift to review and commit).
 */
function writeAgentNameMap(repoRoot) {
  const agents = buildAgentNameMap(repoRoot);
  const serialized = serializeAgentNameMap(agents);
  const file = agentNameMapPath(repoRoot);
  const changed = !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== serialized;
  if (changed) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, serialized, 'utf8');
  }
  return { agents, changed };
}

module.exports = {
  MAP_REL,
  buildAgentNameMap,
  serializeAgentNameMap,
  loadAgentNameMap,
  writeAgentNameMap,
  agentNameMapPath,
};
